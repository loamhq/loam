// Real layout and navigation; every record and mutation is isolated fixture data.
import assert from 'node:assert/strict'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { openingFixture, openingId, openingMessages } from './thread-opening-fixture.mjs'

const out = process.env.THREAD_OPENING_EVIDENCE
if (!out) throw new Error('Set THREAD_OPENING_EVIDENCE')
await mkdir(out, { recursive: true })
const { chromium } = await import(process.env.LOAM_PLAYWRIGHT || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.LOAM_CHROME, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const source = await readFile(new URL('../public/app.js', import.meta.url), 'utf8'), results = []
try {
  for (const width of [390, 1440]) for (const theme of ['light', 'dark']) {
    const app = await openingFixture(), errors = [], screenshots = []
    const context = await browser.newContext({ viewport: { width, height: width === 390 ? 844 : 1000 }, colorScheme: theme, reducedMotion: 'reduce' })
    await context.route('**/app.js', (route) => route.fulfill({ contentType: 'text/javascript', body: source + '\nglobalThis.__opening = { threads, schedule, goChats, goFiles };' }))
    context.on('page', (page) => { page.setDefaultTimeout(15000); page.on('pageerror', (e) => errors.push(e.message)) })
    const settle = (page) => page.evaluate(async () => { await document.fonts.ready; await new Promise(requestAnimationFrame); await new Promise(requestAnimationFrame) })
    const capture = async (page, state) => { await settle(page); const file = `${state}-${width}-${theme}.png`; await page.screenshot({ path: path.join(out, file), animations: 'disabled' }); screenshots.push(file) }
    const anchor = (page) => page.evaluate(async () => (await import('/thread-opening.js')).readingAnchor(document.querySelector('.tt-stream')))
    const offset = (page, id) => page.locator(`[data-message-id="${id}"]`).evaluate((n) => n.getBoundingClientRect().top - n.closest('.tt-stream').getBoundingClientRect().top)
    const page = await context.newPage()
    try {
      await page.goto(app.url); await page.locator('.tt-row').first().waitFor()
      app.holdLatest()
      await page.locator('.tt-row').first().click()
      await page.locator('.tt-opening-note').waitFor()
      assert.equal(await page.locator('.thread-load').count(), 0)
      assert.equal(await page.locator('#draft').getAttribute('contenteditable'), 'true')
      await capture(page, 'opening-shell')
      app.releaseLatest()
      await page.locator('[data-message-id="m37"]').waitFor()
      await capture(page, 'first-paint')
      await page.locator('[data-message-id="m37"] .tt-prose-content:not(.tt-prose-plain)').waitFor()
      await settle(page)
      const landingOffset = await offset(page, 'm37')
      const stripOffset = await page.locator('[data-unread-boundary]').evaluate((n) => n.getBoundingClientRect().top - n.closest('.tt-stream').getBoundingClientRect().top)
      assert.ok(Math.abs(stripOffset - 56) < 2, `unread strip stays at 56 px, got ${stripOffset}`)
      assert.ok(landingOffset > stripOffset && landingOffset < 240)
      assert.equal(await page.locator('[data-unread-boundary="m37"]').innerText(), '2 new from the agents')
      assert.equal(await page.locator('[data-message-id="m36"]').count(), 1, 'the last human thought is loaded with its replies')
      assert.equal(await page.locator('[data-message-id]').count(), 12)
      assert.ok(app.reads.includes('events?after=m38'))
      await capture(page, 'first-unseen')
      app.holdHistory()
      await page.locator('.tt-stream').evaluate((n) => { n.scrollTop = 0; n.dispatchEvent(new Event('scroll')) })
      await page.locator('.tt-history-loading').waitFor()
      const before = await anchor(page)
      await capture(page, 'loading-earlier')
      const afterCapture = await anchor(page)
      app.add({ id: 'm39', author: 'quill', kind: 'message', at: '2026-11-10T13:00:00Z', text: 'Arrived while you were reading earlier.' })
      await page.locator('[data-message-id="m39"]').waitFor({ state: 'attached' })
      app.releaseHistory()
      await page.waitForFunction(() => !__opening.threads.st.open.moreBusy)
      await page.locator('[data-message-id="m1"]').waitFor({ state: 'attached' })
      await settle(page)
      const historyOffset = await offset(page, before.id)
      assert.ok(Math.abs(historyOffset - before.offset) < 2, `history anchor moved ${historyOffset - before.offset} px: ${JSON.stringify({ before, afterCapture, after: await anchor(page), state: await page.evaluate(() => ({ atEnd: __opening.threads.st.open.atEnd, openingBoundary: __opening.threads.st.open.openingBoundary })) })}`)
      assert.equal(await page.locator('.tt-history').count(), 0)
      assert.equal(await page.locator('[data-message-id="m39"]').count(), 1)
      await page.locator('[data-message-id="m20"]').evaluate((n) => { const p = n.closest('.tt-stream'); p.scrollTop += n.getBoundingClientRect().top - p.getBoundingClientRect().top - 64; p.dispatchEvent(new Event('scroll')) })
      await page.locator('[data-message-id="m20"] .tt-prose-content:not(.tt-prose-plain)').waitFor()
      await settle(page)
      const saved = await anchor(page)
      app.holdLatest()
      await page.evaluate((id) => { __opening.threads.close(); __opening.threads.open(id) }, openingId)
      await page.locator(`[data-message-id="${saved.id}"]`).waitFor({ state: 'attached' })
      await settle(page)
      const restoredBeforeRead = await offset(page, saved.id)
      assert.ok(Math.abs(restoredBeforeRead - saved.offset) < 2, `restoration before network moved ${restoredBeforeRead - saved.offset} px`)
      await capture(page, 'restored')
      await page.getByRole('button', { name: 'Board', exact: true }).click()
      await page.getByText('Opening your board…', { exact: true }).waitFor()
      assert.equal(await page.locator('.tt-board-item').count(), 0, 'a cached board cannot be edited before its fresh reading')
      await page.getByRole('button', { name: 'Close board', exact: true }).click()
      app.releaseLatest()
      await page.waitForFunction(() => !__opening.threads.st.open.refreshing)
      await settle(page)
      assert.ok(Math.abs((await offset(page, saved.id)) - saved.offset) < 2)
      assert.ok(app.reads.includes('events?after=m39'))
      await page.evaluate(() => __opening.goFiles('vault', 'notes.md', { isFile: true }))
      await page.waitForURL('**/files/vault/notes.md')
      await page.goBack({ waitUntil: 'domcontentloaded' })
      await page.locator(`[data-message-id="${saved.id}"]`).waitFor({ state: 'attached' })
      await page.waitForFunction(() => !__opening.threads.st.open.refreshing)
      await settle(page)
      assert.ok(Math.abs((await offset(page, saved.id)) - saved.offset) < 2, 'Back from Files restores the thread directly')
      await page.close()
      const cold = await context.newPage()
      await cold.goto(`${app.url}/threads/${openingId}`)
      await cold.locator('[data-message-id="m38"] .tt-prose-content:not(.tt-prose-plain)').waitFor()
      await settle(cold)
      assert.ok((await offset(cold, 'm38')) < 240, 'cold deep link uses the pre-read listing count too')
      await capture(cold, 'cold-load')
      await cold.reload({ waitUntil: 'domcontentloaded' })
      await cold.locator('[data-unread-boundary="m38"]').waitFor()
      await cold.locator('[data-message-id="m38"] .tt-prose-content:not(.tt-prose-plain)').waitFor()
      await settle(cold)
      assert.ok((await offset(cold, 'm38')) < 240, 'reload lands by the same rule')
      await cold.close()
      app.row.unread = 0
      const caughtUp = await context.newPage()
      await caughtUp.goto(app.url); await caughtUp.locator('.tt-row').first().click()
      await caughtUp.locator('[data-message-id="m39"]').waitFor()
      await settle(caughtUp)
      const bottom = await caughtUp.locator('.tt-stream').evaluate((n) => n.scrollHeight - n.scrollTop - n.clientHeight)
      assert.ok(bottom <= 2, `all seen opens at the end, gap ${bottom}`)
      assert.equal(await caughtUp.locator('.tt-unread-strip').count(), 0)
      await capture(caughtUp, 'caught-up')
      await caughtUp.close()
      const bridge = await context.newPage()
      await bridge.goto(app.url); await bridge.locator('.tt-row').first().waitFor()
      app.holdLatest(); const count = app.reads.length
      await bridge.locator('.tt-row').first().click(); await bridge.locator('.tt-opening-note').waitFor()
      while (app.reads.length === count) await new Promise((r) => setTimeout(r, 5))
      app.add({ id: 'm40', author: 'sprout', kind: 'message', at: '2026-11-10T13:01:00Z', text: 'A reply between reading and attaching.' }, false)
      app.releaseLatest()
      await bridge.locator('[data-message-id="m40"]').waitFor()
      assert.equal(await bridge.locator('[data-message-id="m40"]').count(), 1)
      assert.ok(app.reads.slice(count).includes('events?after=m39'))
      await bridge.goBack({ waitUntil: 'domcontentloaded' }); await bridge.locator('.tt-row').first().waitFor()
      await bridge.locator('.tt-thread').waitFor({ state: 'detached' })
      assert.equal(await bridge.locator('.tt-thread').count(), 0)
      await bridge.goForward({ waitUntil: 'domcontentloaded' }); await bridge.locator('[data-message-id="m40"]').waitFor()
      const grown = [...openingMessages, ...Array.from({ length: 26 }, (_, i) => ({ id: `m${i + 39}`, author: 'quill', kind: 'message', text: `A later reply ${i + 39}.` }))]
      await bridge.evaluate(() => __opening.threads.close())
      app.setMessages(grown)
      await bridge.evaluate((id) => __opening.threads.open(id), openingId)
      await bridge.waitForFunction(() => !__opening.threads.st.open.gapBefore && !__opening.threads.st.open.moreBusy)
      const joined = await bridge.evaluate(() => __opening.threads.st.open.messages.map((m) => m.id))
      const firstJoined = grown.findIndex((m) => m.id === joined[0])
      assert.ok(firstJoined <= 22, 'the gap page reaches above the saved tail')
      assert.deepEqual(joined, grown.slice(firstJoined).map((m) => m.id), 'a gap page extending above saved history stays in record order')
      assert.ok(app.reads.includes('events?after=m64'))
      await bridge.close()
      // More than one page of replies follows the person's last thought.
      // Paint the tail now, then collect that context without blocking it.
      app.setMessages(openingMessages.map((m, i) => ({ ...m, author: i === 0 ? 'you' : 'quill' })))
      app.holdHistory()
      const contextPage = await context.newPage()
      await contextPage.goto(app.url); await contextPage.locator('.tt-row').first().click()
      await contextPage.locator('[data-message-id="m38"]').waitFor()
      await contextPage.locator('.tt-history-loading').waitFor({ state: 'attached' })
      assert.equal(await contextPage.locator('[data-message-id]').count(), 12, 'first paint does not wait for the earlier context')
      app.releaseHistory()
      await contextPage.locator('[data-message-id="m1"]').waitFor({ state: 'attached' })
      assert.equal(await contextPage.locator('[data-message-id]').count(), 38, 'all replies since the last person’s thought are present')
      await contextPage.close()
      assert.deepEqual(errors, [])
      assert.ok(app.writes.every((w) => w.seen === true), 'only expected fixture read marks occur')
      results.push({ width, theme, landingOffset, historyAnchorDelta: historyOffset - before.offset, restorationDeltaBeforeRead: restoredBeforeRead - saved.offset,
        composerReadyWhileReading: true, initialMessages: 12, unseenFromPreReadCount: true, autoHistory: true, noEndOfHistoryAffordance: true, liveDuringHistoryDeduplicated: true,
        newestAttach: true, readAttachGapReplayedOnce: true, coldAndReloadSameLanding: true, backForward: true, filesBackRestores: true,
        contextAfterFirstPaint: true, gapOverlapInOrder: true, caughtUpAtEnd: true, screenshots, pageErrors: errors })
    } finally { app.releaseHistory(); app.releaseLatest(); await context.close(); await app.close() }
  }
} finally { await browser.close() }
await writeFile(path.join(out, 'browser.json'), JSON.stringify(results, null, 2) + '\n')
console.log(JSON.stringify(results, null, 2))
