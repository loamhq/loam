import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { oneProductFixture } from './one-product-fixture.mjs'
import { renameHost } from './fixtures/files-rename.js'

const out = process.env.FILES_RENAME_EVIDENCE
assert.ok(out, 'Set FILES_RENAME_EVIDENCE to a retained evidence directory')
await mkdir(out, { recursive: true })
const { chromium } = await import(process.env.LOAM_PLAYWRIGHT || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.LOAM_CHROME, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const source = await readFile('public/app.js', 'utf8'), reports = []
const json = (res, body) => { res.writeHead(200, { 'content-type': 'application/json' }); res.end(JSON.stringify(body)) }
try {
  for (const width of [390, 1440]) for (const look of ['latte', 'plain']) for (const mode of ['light', 'dark']) {
    const app = await oneProductFixture(), host = renameHost(), label = `${width}-${look}-${mode}`, errors = []
    Object.assign(app.routes, host.routes)
    app.routes['GET /v1/settings/appearance'] = (req, res) => json(res, { phone: { mode, theme: look, size: 100 }, desktop: { mode, theme: look, size: 100 } })
    const context = await browser.newContext({ viewport: { width, height: width === 390 ? 844 : 1000 }, colorScheme: mode, reducedMotion: 'reduce', isMobile: width === 390, hasTouch: width === 390 })
    await context.route('**/app.js', route => route.fulfill({ contentType: 'text/javascript', body: source + '\nglobalThis.__rename = { files, store, goFiles, schedule };' }))
    const page = await context.newPage()
    page.setDefaultTimeout(10000)
    page.on('pageerror', error => errors.push(error.message))
    page.on('dialog', dialog => { errors.push(`Unexpected native dialog: ${dialog.message()}`); dialog.dismiss() })
    const shot = async name => {
      await page.evaluate(async () => { await document.fonts.ready; await new Promise(requestAnimationFrame) })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, label + ': horizontal overflow')
      await page.screenshot({ path: path.join(out, `${name}-${label}.png`), animations: 'disabled' })
    }
    const field = page.locator('.fs-rename-input')
    try {
      await page.goto(`${app.url}/files/vault/Notes/plan.md`)
      await page.waitForFunction(() => globalThis.__rename && !__rename.files.st.file?.loading)
      await page.locator('.fs-rename-start.fs-edtitle').waitFor()
      await page.evaluate(() => { __rename.store.files = { ...__rename.store.files, shortcuts: [{ root: 'vault', path: 'Notes/plan.md', kind: 'file' }, { root: 'vault', path: 'Notes/Old' }, { root: 'vault', path: 'Notes/Old/child.md', kind: 'file' }] } })
      await page.locator('.fs-rename-start.fs-edtitle').click()
      await field.waitFor()
      await page.waitForFunction(() => document.activeElement?.classList.contains('fs-rename-input'))
      assert.deepEqual(await field.evaluate(n => [n.selectionStart, n.selectionEnd, n.value]), [0, 4, 'plan.md'])
      await shot('title-edit')
      await field.fill('cancelled')
      await field.press('Escape')
      await field.waitFor({ state: 'detached' })
      assert.equal(host.renames.length, 0)
      await page.locator('.fs-rename-start.fs-edtitle').click()
      await field.fill('cancelled by button')
      const cancel = page.getByRole('button', { name: 'Cancel rename', exact: true })
      if (width === 390) await cancel.tap()
      else await cancel.click()
      await field.waitFor({ state: 'detached' })
      assert.equal(host.renames.length, 0)

      await page.locator('.fs-filemenu').last().click()
      await page.getByRole('button', { name: 'Rename', exact: true }).waitFor()
      await shot('file-menu')
      await page.getByRole('button', { name: 'Rename', exact: true }).click()
      await field.fill('Taken')
      await field.press('Enter')
      await page.locator('.fs-rename-error').filter({ hasText: 'already exists; choose another name' }).waitFor()
      assert.equal(new URL(page.url()).pathname, '/files/vault/Notes/plan.md')
      assert.equal(await field.inputValue(), 'Taken')
      assert.equal(await field.evaluate(n => document.activeElement === n), true, 'An error keeps typing focus')
      await shot('inline-error')
      await field.fill('')
      await field.press('Enter')
      await page.locator('.fs-rename-error').filter({ hasText: 'Choose a name' }).waitFor()
      await field.fill('Final draft')
      await field.press('Enter')
      await page.waitForURL('**/files/vault/Notes/Final%20draft.md')
      await field.waitFor({ state: 'detached' })
      assert.equal(host.renames.length, 3, 'Enter and blur must not double submit')
      assert.equal(host.renames.at(-1).name, 'Final draft.md')
      assert.equal(host.texts.has('Notes/plan.md'), false)
      assert.equal(await page.evaluate(() => __rename.store.files.shortcuts[0].path), 'Notes/Final draft.md')
      await shot('renamed-viewer')

      // Open the same file in a second tab. A renamed folder/file must update
      // its address and document without losing any of that tab's draft.
      const other = await context.newPage()
      await other.goto(page.url())
      await other.waitForFunction(() => globalThis.__rename && __rename.files.st.file && !__rename.files.st.file.loading)
      await page.evaluate(() => __rename.files.setMode('edit'))
      const editor = page.locator('.fs-field')
      await editor.fill('Words typed before the rename. Still here afterwards.')
      await page.locator('.fs-rename-start.fs-edtitle').click()
      await field.fill('Working.txt')
      await page.locator('.fs-sub').first().click() // blur saves
      await page.waitForURL('**/files/vault/Notes/Working.txt')
      await other.waitForURL('**/files/vault/Notes/Working.txt')
      await page.waitForFunction(() => !__rename.files.dirty() && !__rename.files.st.file.saving)
      assert.equal(host.texts.get('Notes/Working.txt'), 'Words typed before the rename. Still here afterwards.')
      await shot('renamed-editor')
      await page.reload()
      await page.waitForFunction(() => globalThis.__rename && __rename.files.st.file && !__rename.files.st.file.loading)
      assert.equal(await editor.inputValue(), host.texts.get('Notes/Working.txt'))
      assert.equal(await page.evaluate(() => __rename.store.files.shortcuts[0].path), 'Notes/Working.txt')

      await other.goto(`${app.url}/files/vault/Notes/Old/child.md`)
      await other.waitForFunction(() => globalThis.__rename && __rename.files.st.file && !__rename.files.st.file.loading)
      await page.evaluate(() => __rename.goFiles('vault', 'Notes'))
      await page.getByRole('button', { name: 'Actions for Old', exact: true }).click()
      await page.getByRole('button', { name: 'Rename', exact: true }).click()
      await field.fill('Research.v2')
      await field.press('Enter')
      await field.waitFor({ state: 'detached' })
      await other.waitForURL('**/files/vault/Notes/Research.v2/child.md')
      assert.deepEqual(await page.evaluate(() => __rename.store.files.shortcuts.map(s => s.path)), ['Notes/Working.txt', 'Notes/Research.v2', 'Notes/Research.v2/child.md'])
      assert.equal(host.texts.get('Notes/Research.v2/child.md'), '# A child note\n\nStill here.')
      await other.close()

      // Shortcut menus obtain capability from stat, then rename in their row.
      await page.evaluate(() => __rename.goFiles(null, ''))
      await page.getByRole('button', { name: 'Shortcut actions for Research.v2', exact: true }).click()
      await page.getByRole('button', { name: 'Rename', exact: true }).click()
      await field.fill('Research')
      await field.press('Enter')
      await field.waitFor({ state: 'detached' })
      assert.equal(host.entries.has('Notes/Research/child.md'), true)
      await page.evaluate(() => __rename.goFiles('vault', 'Notes/Research'))
      await page.locator('.fs-menu').click()
      await page.getByRole('button', { name: 'Rename', exact: true }).click()
      await field.fill('Collected notes')
      await field.press('Enter')
      await page.waitForURL('**/files/vault/Notes/Collected%20notes')
      assert.equal(host.entries.has('Notes/Collected notes/child.md'), true)
      await page.evaluate(() => __rename.goFiles('vault', 'Notes'))
      await page.getByRole('button', { name: 'Actions for Taken.md', exact: true }).click()
      await page.getByRole('button', { name: 'Rename', exact: true }).click()
      await field.fill('Meeting notes')
      await shot('list-row-edit')
      await page.getByRole('button', { name: 'Save name', exact: true }).click()
      await field.waitFor({ state: 'detached' })
      assert.equal(host.texts.get('Notes/Meeting notes.md'), '# Already here')
      await page.evaluate(() => __rename.goFiles(null, ''))
      await page.reload()
      await page.getByRole('button', { name: 'Shortcut actions for Meeting notes.md', exact: true }).waitFor()
      assert.equal(await page.getByRole('button', { name: 'Shortcut actions for Reading note', exact: true }).count(), 0, 'Old host suggestion stays dismissed on reload')
      await page.evaluate(() => __rename.goFiles('vault', 'Notes/pinned.md', { isFile: true }))
      await page.waitForFunction(() => __rename.files.st.file && !__rename.files.st.file.loading)
      assert.equal(await page.locator('.fs-rename-start.fs-edtitle').count(), 0)
      await page.locator('.fs-filemenu').last().click()
      assert.equal(await page.locator('.fs-menu-rename').count(), 0)
      await page.keyboard.press('Escape')

      await page.evaluate(() => __rename.goFiles('vault', 'Notes/page.html', { isFile: true }))
      await page.locator('.fs-htmlname.fs-rename-start').waitFor()
      await page.locator('.fs-htmlname.fs-rename-start').click()
      await field.fill('A quiet page')
      await shot('html-title-edit')
      await field.press('Enter')
      await page.waitForURL('**/files/vault/Notes/A%20quiet%20page.html')
      assert.equal(host.entries.has('Notes/A quiet page.html'), true)
      assert.deepEqual(errors, [])
      reports.push({ label, renames: host.renames.length, writes: host.puts.length, errors, checks: 'title selection, Escape/touch cancel, menu, conflict/blank errors with focus retained, Enter once, extension retention/change, blur, editor words/reload, persisted personal and suggested shortcuts, second tab, folder descendants, shortcut/current-folder/file-row rename, pinned omission, HTML header' })
      console.log(`PASS ${label}`)
    } finally { await context.close(); await app.close() }
  }
  await writeFile(path.join(out, 'checks.json'), JSON.stringify(reports, null, 2) + '\n')
  console.log(`Passed ${reports.length} width/theme/mode variants`)
} finally { await browser.close() }
