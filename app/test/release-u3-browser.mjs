import assert from 'node:assert/strict'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { u3Fixture } from './release-u3-fixture.mjs'
const { chromium } = await import(process.env.LOAM_PLAYWRIGHT || 'playwright')
const out = process.env.U3_EVIDENCE || `${process.env.TMPDIR}/u3`
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.LOAM_CHROME, args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const source = await readFile('public/app.js', 'utf8'), reports = []
try {
  for (const width of [390, 1440].filter(w => !process.env.U3_WIDTH || w === Number(process.env.U3_WIDTH))) for (const mode of ['light', 'dark'].filter(m => !process.env.U3_MODE || m === process.env.U3_MODE)) {
    const app = await u3Fixture(), context = await browser.newContext({ viewport: { width, height: width === 390 ? 844 : 940 }, colorScheme: mode, serviceWorkers: 'block', reducedMotion: 'reduce' })
    const page = await context.newPage(), errors = [], external = []
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', e => { if (e.type() === 'error') errors.push(`${e.text()} ${e.location().url}`) })
    await context.route('**/*', async r => {
      const url = new URL(r.request().url())
      if (url.origin !== app.url) { external.push(url.href); return r.abort() }
      if (url.pathname === '/app.js') return r.fulfill({ contentType: 'text/javascript', body: source + '\nglobalThis.__u3={state,profiles,settingsProfiles,goProfile,goSettings,schedule,threads,pluginLoader,files,goFiles,dailyNotes,theme};' })
      return r.continue()
    })
    const shot = async name => { await page.screenshot({ path: `${out}/${name}-${width}-${mode}.png` }); console.log(`${width} ${mode}: ${name}`) }
    try {
      await page.goto(app.url)
      await page.waitForFunction(() => globalThis.__u3?.state.agentsReady && !__u3.pluginLoader.st.loading)
      await page.evaluate(() => __u3.goProfile('sprout'))
      await page.getByText('From the soul', { exact: true }).waitFor()
      assert.equal(await page.getByRole('tab', { selected: true }).textContent(), 'Threads')
      assert.ok(!(await page.locator('.profile-soul').textContent()).includes('third sentence'))
      await shot('profile-threads')
      for (const tab of ['Schedules', 'Settings', 'Files']) {
        await page.getByRole('tab', { name: tab, exact: true }).click()
        if (tab === 'Settings') await page.getByLabel('Voice', { exact: true }).waitFor()
        await shot(`profile-${tab.toLowerCase()}`)
      }
      await page.getByRole('button', { name: 'Read soul', exact: true }).click()
      await page.waitForFunction(() => __u3.files.st.file?.path === 'sprout/soul.md' && !__u3.files.st.file.loading)
      await shot('read-soul')
      await page.evaluate(() => __u3.goProfile('sprout'))
      await page.getByRole('button', { name: 'Change by talking', exact: true }).click()
      await page.waitForFunction(() => __u3.threads.st.open && !__u3.threads.st.open.creating)
      assert.equal(await page.evaluate(() => __u3.threads.st.open.messages.length), 0)
      await page.getByText('I’d like to change your soul.', { exact: false }).waitFor()
      await shot('change-by-talking')
      await page.evaluate(() => __u3.goProfile('sprout'))
      await page.getByRole('tab', { name: 'Threads', exact: true }).click()
      await page.evaluate(() => {
        const original = __u3.threads.st.threads.find(t => t.default === 'sprout')
        __u3.threads.st.threads.push(...Array.from({ length: 27 }, (_, i) => ({ ...original, id: `page-test-${i}`, title: `A useful thread ${i}` })))
        __u3.schedule()
      })
      await page.getByRole('button', { name: 'Next', exact: true }).click()
      await page.getByText('2 / 3', { exact: true }).waitFor()
      const before = await page.locator('.profile-hero').boundingBox()
      await page.locator('.profile-tab-content').evaluate(n => n.scrollTop = n.scrollHeight)
      assert.deepEqual(await page.locator('.profile-hero').boundingBox(), before)
      assert.equal(await page.locator('.profile-tab-content .tt-row').count(), 12)
      await shot('profile-paged')
      await page.evaluate(() => __u3.goSettings('agents'))
      await page.getByRole('button', { name: 'New agent', exact: true }).waitFor()
      await shot('agents')
      if (width === 1440) {
        await page.locator('.setmain .setrow').filter({ has: page.getByText('Sprout', { exact: true }) }).click()
        await page.getByRole('tab', { name: 'Threads', exact: true }).waitFor()
        await page.locator('.setmain').getByText('From the soul', { exact: true }).waitFor()
        const modalHero = page.locator('.setmain .profile-hero'), modalBefore = await modalHero.boundingBox()
        await page.locator('.setmain .profile-tab-content').evaluate(n => n.scrollTop = n.scrollHeight)
        assert.deepEqual(await modalHero.boundingBox(), modalBefore)
        await shot('profile-in-settings')
        await page.locator('.setmain .backbtn').click()
      }
      await page.getByRole('button', { name: 'New agent', exact: true }).click()
      await page.getByText('Start by telling the agent what you have in mind. Its draft will appear here for your review.', { exact: true }).waitFor()
      assert.equal(await page.evaluate(() => __u3.threads.st.open.messages.length), 0, 'the person writes first')
      await page.locator('#draft').fill('Make a small agent that asks useful questions.')
      await page.getByTitle('Send', { exact: true }).first().click()
      await page.getByRole('button', { name: 'Create agent', exact: true }).waitFor()
      await shot('agent-review')
      await page.getByRole('button', { name: 'Create agent', exact: true }).click()
      await page.getByText('Throwaway is ready.', { exact: true }).waitFor()
      await page.evaluate(() => __u3.goProfile('throwaway'))
      await page.getByRole('button', { name: 'Rename Throwaway', exact: true }).click()
      await page.getByLabel('Display name', { exact: true }).fill('Little Green')
      await page.getByRole('button', { name: 'Save', exact: true }).click()
      await page.getByRole('button', { name: 'Rename Little Green', exact: true }).waitFor()
      await page.getByRole('button', { name: 'Change Little Green’s face', exact: true }).click()
      await page.getByLabel('Upload face', { exact: true }).setInputFiles({ name: 'face.png', mimeType: 'image/png', buffer: app.pixel })
      await page.locator('.profile-face img').waitFor()
      const image = await page.locator('.profile-face img').getAttribute('src')
      await page.evaluate(() => { __u3.theme.set({ theme: 'plain' }) })
      assert.equal(await page.locator('.profile-face img').getAttribute('src'), image)
      await shot('uploaded-face')
      await page.evaluate(() => { __u3.theme.set({ theme: 'latte' }) })
      await page.getByRole('button', { name: 'Change Little Green’s face', exact: true }).click()
      await page.getByRole('button', { name: 'Remove uploaded face', exact: true }).click()
      await page.locator('.profile-face:not(:has(img))').waitFor()
      await page.getByLabel('Agent actions', { exact: true }).click()
      await page.getByRole('menuitem', { name: 'Archive agent', exact: true }).click()
      await page.getByRole('alertdialog').waitFor()
      await shot('archive-confirm')
      let release
      app.state.archiveHeld = new Promise(r => { release = r })
      await page.getByRole('button', { name: 'Archive', exact: true }).click()
      await page.getByText('Archiving… This can take up to 20 minutes. Keep this page open.', { exact: true }).waitFor()
      await shot('archive-progress'); release()
      await page.waitForFunction(() => !__u3.state.agents.byId.has('throwaway'))
      await page.evaluate(() => __u3.goSettings('agents'))
      await page.getByRole('button', { name: 'Archived', exact: true }).click()
      await page.getByRole('button', { name: 'Restore Little Green', exact: true }).waitFor()
      await shot('archived')
      await page.getByRole('button', { name: 'Restore Little Green', exact: true }).click()
      await page.getByText('No archived agents.', { exact: true }).waitFor()
      assert.equal(app.state.archived, false)
      await page.evaluate(() => __u3.goSettings('voice'))
      await page.getByLabel('Gemini API key for dictation', { exact: true }).waitFor()
      await page.getByLabel('Gemini API key for dictation', { exact: true }).scrollIntoViewIfNeeded()
      await shot('voice-keys')
      await page.getByLabel('Gemini API key for read-aloud', { exact: true }).scrollIntoViewIfNeeded()
      await shot('read-aloud-key')
      const keySection = page.getByRole('region', { name: 'dictation API key', exact: true })
      await keySection.getByLabel('Gemini API key for dictation', { exact: true }).fill('synthetic-key-for-fixture')
      await keySection.getByRole('button', { name: 'Save key', exact: true }).click()
      await keySection.getByText('A key is saved for this plugin.', { exact: true }).waitFor()
      assert.equal(await keySection.locator('input').inputValue(), '')
      await keySection.getByRole('button', { name: 'Check again', exact: true }).click()
      await keySection.getByRole('button', { name: 'Forget', exact: true }).click()
      await keySection.getByText('Using the key supplied by this box.', { exact: true }).first().waitFor()
      await page.evaluate(() => __u3.goSettings('plugins'))
      await page.getByRole('button', { name: 'About Daily notes', exact: true }).click()
      await page.getByLabel('Daily notes folder', { exact: true }).waitFor()
      await shot('daily-settings')
      await page.getByLabel('Daily notes folder', { exact: true }).fill('Days')
      await page.getByRole('button', { name: 'Save folder', exact: true }).click()
      await page.waitForFunction(() => __u3.dailyNotes.st.folder === 'Days')
      await page.getByRole('switch', { name: 'Enable daily notes', exact: true }).click()
      await page.waitForFunction(() => !__u3.dailyNotes.st.on)
      await page.evaluate(() => { __u3.state.sheet = null; __u3.goFiles() })
      await page.locator('.fs-homehead').first().waitFor()
      assert.equal(await page.getByRole('button', { name: /Open daily note/ }).count(), 0)
      app.state.daily.on = true
      await page.evaluate(() => __u3.dailyNotes.refresh())
      await page.getByRole('button', { name: /Open daily note/ }).click()
      await page.waitForFunction(() => __u3.files.st.file?.path.startsWith('Days/') && !__u3.files.st.file.loading)
      assert.match(await page.evaluate(() => __u3.files.st.file.path), /^Days\/\d{4}-\d{2}-\d{2}\.md$/)
      await shot('daily-note')
      app.cleanupThrowaway()
      assert.deepEqual(app.state.lifecycle, ['conversation', 'created', 'archived', 'restored', 'removed'])
      assert.deepEqual(errors, [])
      assert.deepEqual(external, [])
      reports.push({ width, mode, lifecycle: app.state.lifecycle, errors, external })
    } catch (e) { await shot('failure'); throw e }
    finally { await context.close(); await app.close() }
  }
  await writeFile(`${out}/results.json`, JSON.stringify(reports, null, 2))
} finally { await browser.close() }
