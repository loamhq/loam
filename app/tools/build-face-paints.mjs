// Variant pigments are material colours, independent of the agent palette.
import { readFile, writeFile } from 'node:fs/promises'
import { contrast } from './theme-contrast.mjs'
const paints=JSON.parse(await readFile(new URL('./face-paints.json',import.meta.url)))
const rgb=hex=>hex.slice(1).match(/../g).map(v=>parseInt(v,16))
const mix=(a,b,share)=>'#'+rgb(a).map((v,i)=>Math.round(v*share+rgb(b)[i]*(1-share)).toString(16).padStart(2,'0')).join('').toUpperCase()
const blocks=[]
for(const [theme,modes]of Object.entries(paints)) for(const [mode,variants]of Object.entries(modes)) {
  if(variants.length!==8)throw Error('Eight permanent paint slots required')
  variants.forEach((paint,n)=>{
    const [body,sky,cloud]=Array.isArray(paint)?paint:[paint]
    const inks=theme==='autumn'?['#100803']:['#070E0A','#FFF9ED']
    const ink=inks.sort((a,b)=>contrast(b,body)-contrast(a,body))[0]
    if(contrast(ink,body)<4.5)throw Error(`Initial contrast: ${theme}/${mode}/${n}`)
    let edge=theme==='deep-forest'?mix(body,'#243126',.25):mix(body,'#21373C',.65)
    // Granite initials can cross a facet: both must carry the same AA ink.
    if(theme==='yosemite') { let share=.65;while(contrast(ink,edge)<4.5)edge=mix(body,'#21373C',share+=.025) }
    const values={'face-body':body,'face-ink':ink,'face-edge':edge,'face-line':mix(ink,body,.53),'face-light':mode==='dark'?'#C8D8D2':'#F7FBF6'}
    if(theme==='deep-forest')values['face-line']=contrast('#070E0A',body)<4.5?mix(body,'#DFBE8B',.55):mix(body,'#574026',.6)
    if(theme==='mist-trail') Object.assign(values,{'face-moss':mode==='dark'?'#526B3B':'#677B40','face-quartz':mode==='dark'?'#C3CEBC':'#F1F0DE'})
    if(theme==='yosemite')Object.assign(values,{'face-sky':sky,'face-cloud':cloud})
    if(theme==='autumn') { values[`face-leaf-${n}`]=body;delete values['face-edge'];delete values['face-line'];delete values['face-light'] }
    blocks.push(`:root[data-look="${theme}"][data-theme="${mode}"] .blob[data-face-variant="${n}"] {\n${Object.entries(values).map(([k,v])=>`  --${k}: ${v};`).join('\n')}\n}`)
  })
}
await writeFile(new URL('../public/themes/face-paints.css',import.meta.url),'/* Generated by tools/build-face-paints.mjs from tools/face-paints.json. */\n'+blocks.join('\n\n')+'\n')
console.log('Generated 64 material paints; initials AA, including granite facets.')
