// Paid, maintainer-only recording. Uses the existing broker secret in memory;
// no credential or provider response is written to disk or printed.
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { setTimeout as sleep } from 'node:timers/promises'
import { readConfig } from '../src/config.js'
import { createBroker } from '../src/broker.js'
import { brokerSecret } from '../src/plugin-secrets.js'
import { createSpeech, DEFAULT_VOICE } from '../src/speech.js'
import { PREBUILT_VOICES } from '../public/plugins/read-aloud/page/document-speech.js'
import { sampleText } from '../public/plugins/read-aloud/page/voice-samples.js'

if (process.argv.slice(2).join(' ') !== '--record') {
  console.log('Usage: BROKER_URL=… BROKER_TOKEN=… SPEECH_DIR=<scratch cache> node tools/record-voice-samples.mjs --record')
  console.log('Makes 30 paid Gemini TTS recordings using the runtime read-aloud plugin key. Requires ffmpeg.')
  process.exit(0)
}
const config = readConfig()
if (!config.brokerUrl || !config.brokerToken || !process.env.SPEECH_DIR) throw new Error('Recording requires BROKER_URL, BROKER_TOKEN and an explicit scratch SPEECH_DIR.')
const getKey = brokerSecret(createBroker(config), 'read-aloud')
if (!await getKey()) throw new Error('The read-aloud plugin key is unavailable from the configured broker.')
const speech = createSpeech(config, { getKey })
const root = fileURLToPath(new URL('../public/plugins/read-aloud/', import.meta.url))
const staged = [], samples = {}
try {
  for (const voice of PREBUILT_VOICES) {
    // Reuses model selection, annotation, PCM validation, 64k MP3 encoding
    // and loudness normalization from the real Full reply path.
    const out = await speech.request({ chat_id: 'voice-samples', agent: 'voice-samples', text: sampleText, mode: 'verbatim', voice, style: DEFAULT_VOICE.character })
    if (![200, 202].includes(out.status)) throw new Error(`Recording ${voice} could not start (${out.status}; ${out.body.reason || 'refused'}).`)
    let result = out.body
    const deadline = Date.now() + 180000
    while (result.status === 'preparing' && Date.now() < deadline) { await sleep(250); result = await speech.lookup(out.body.id) }
    if (result?.status !== 'ready') throw new Error(`Recording ${voice} did not finish. No sample index was published.`)
    if (result.duration_s < 3 || result.duration_s > 5) throw new Error(`${voice} is ${result.duration_s}s; expected 3–5s. Review the take before publishing.`)
    const meta = JSON.parse(await fs.readFile(path.join(config.speech.dir, `${out.body.id}.json`), 'utf8'))
    const bytes = await fs.readFile(path.join(config.speech.dir, `${out.body.id}.mp3`))
    const file = `${voice}-${out.body.id.slice(0, 12)}.mp3`
    staged.push({ file, bytes })
    samples[voice] = { file: `../samples/${file}`, duration_s: result.duration_s, bytes: bytes.length, model: meta.tts_model }
    console.log(`${voice}: ${result.duration_s}s, ${bytes.length} bytes`)
  }
  // No partially populated index: publish only after all voices pass. Named
  // files include the take id, so replacing the index cannot change a playing
  // sample underneath an older page.
  await fs.mkdir(path.join(root, 'samples'), { recursive: true })
  for (const { file, bytes } of staged) await fs.writeFile(path.join(root, 'samples', file), bytes)
  const index = path.join(root, 'page/voice-samples.js')
  await fs.writeFile(index + '.tmp', `// Generated by tools/record-voice-samples.mjs. Do not edit.\nexport const sampleText = ${JSON.stringify(sampleText)}\nexport const samples = ${JSON.stringify(samples, null, 2)}\n`)
  await fs.rename(index + '.tmp', index)
  console.log(`Published ${staged.length} static voice samples. Listen to each before committing.`)
} finally { await speech.stop() }
