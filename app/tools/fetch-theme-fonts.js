// Asset preparation only: self-host Latin/Latin-ext SIL OFL display faces.
// Run node tools/fetch-theme-fonts.js; no font vendor is contacted at runtime.
import { mkdir, writeFile } from 'node:fs/promises'
import { newThemes } from './new-themes.js'
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
for (const theme of newThemes) {
  const folder = new URL(`../public/themes/${theme.id}/`, import.meta.url)
  await mkdir(folder, { recursive: true })
  const family = theme.font.replaceAll(' ', '+')
  const query = theme.id === 'deep-forest' ? 'Fraunces:opsz,wght@24,550' : `${family}:wght@${theme.weight}`
  const response = await fetch(`https://fonts.googleapis.com/css2?family=${query}&display=swap`, { headers: { 'user-agent': UA } })
  if (!response.ok) throw new Error(`Font CSS: ${response.status} ${theme.font}`)
  const css = await response.text(), blocks = css.split(/\/\*\s*([a-z-]+)\s*\*\//i).slice(1), faces = []
  for (let i = 0; i < blocks.length; i += 2) {
    const subset = blocks[i], face = blocks[i + 1]
    if (!['latin', 'latin-ext'].includes(subset)) continue
    const url = /url\((https:\/\/[^)]+\.woff2)\)/.exec(face)?.[1]
    if (!url) throw new Error(`No WOFF2: ${theme.font} ${subset}`)
    const bytes = await fetch(url)
    if (!bytes.ok) throw new Error(`Font bytes: ${bytes.status}`)
    const name = `display-${subset}.woff2`
    await writeFile(new URL(name, folder), Buffer.from(await bytes.arrayBuffer()))
    // Preserve Google's weight descriptor, including variable files: a 400
    // display slot then selects the approved heavier face by font matching.
    faces.push(`/* ${subset} */${face.replace(/url\(https:\/\/[^)]+\.woff2\)/, `url(/themes/${theme.id}/${name})`).trimEnd()}`)
  }
  if (faces.length !== 2) throw new Error(`Expected two subsets: ${theme.font}`)
  await writeFile(new URL('fonts.css', folder), '/* Generated by tools/fetch-theme-fonts.js. */\n' + faces.join('\n') + '\n')
  const oflName = theme.font.toLowerCase().replaceAll(' ', '')
  const license = await fetch(`https://raw.githubusercontent.com/google/fonts/main/ofl/${oflName}/OFL.txt`)
  if (!license.ok) throw new Error(`Missing OFL: ${theme.font}`)
  await writeFile(new URL('OFL.txt', folder), (await license.text()).replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, ''))
  console.log(`Fetched ${theme.font} ${theme.weight}: Latin, Latin-ext and OFL.`)
}
