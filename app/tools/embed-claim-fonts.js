// The claim service serves one standalone file. Keep its Latin faces in sync
// with the bundled theme fonts without giving the claim CSP any network access.
// Run node tools/embed-claim-fonts.js after refreshing public/fonts/.
import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const css = await readFile(new URL('public/fonts/fonts.css', root), 'utf8')
const faces = []
for (const [family, weight] of [['Caprasimo', '400'], ['Figtree', '300 900']]) {
  const face = [...css.matchAll(/\/\* latin \*\/\s*(@font-face\s*\{[^}]+\})/g)]
    .find(([, block]) => block.includes(`font-family: '${family}'`) && block.includes('font-weight: 400;'))?.[1]
  if (!face) throw new Error(`No bundled Latin face for ${family}`)
  const path = face.match(/url\(([^)]+)\)/)[1]
  const bytes = await readFile(new URL(`public${path}`, root))
  faces.push(face.replace('font-weight: 400;', `font-weight: ${weight};`)
    .replace(`url(${path})`, `url(data:font/woff2;base64,${bytes.toString('base64')})`))
}
const block = `/* claim-fonts:start — generated by tools/embed-claim-fonts.js */\n${faces.join('\n')}\n/* claim-fonts:end */`
const file = new URL('public/claim.html', root)
const source = await readFile(file, 'utf8')
const marker = /\/\* claim-fonts:start[^]*?\/\* claim-fonts:end \*\//
if (!marker.test(source)) throw new Error('Missing claim font markers')
const next = source.replace(marker, () => block)
if (process.argv.includes('--check')) {
  if (source !== next) throw new Error('Claim fonts have drifted; run node tools/embed-claim-fonts.js')
  console.log('Claim Latin fonts match the bundled faces.')
} else {
  await writeFile(file, next)
  console.log(`Embedded two Latin faces; claim.html is ${Buffer.byteLength(next)} bytes.`)
}
