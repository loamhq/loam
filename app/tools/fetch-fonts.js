// The generator for `public/fonts/`. The three typefaces the design names —
// Caprasimo, Figtree 400/600/700, JetBrains Mono 400/500 — are served by this
// app and never fetched from a third party at run time. Two reasons, and both
// are binding rather than tidiness: the page's content security policy is
// `default-src 'self'`, so a stylesheet from elsewhere would simply be refused;
// and a page reached from a phone on a bad connection should not wait on
// somebody else's CDN to know what it looks like.
//
//   node tools/fetch-fonts.js
//
// It rewrites `public/fonts/fonts.css` and the `.woff2` files beside it. Edit
// here, never there. Only the `latin` and `latin-ext` subsets are kept: the
// rest are a megabyte of alphabets this app has no copy in.
//
// It needs the network, which the app itself never does.

import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'public', 'fonts')
const SOURCE =
  'https://fonts.googleapis.com/css2?family=Caprasimo&family=Figtree:wght@400;600;700&family=JetBrains+Mono:wght@400;500&display=swap'
// Google answers with whatever formats the asking browser admits to. Ask as one
// that takes woff2, which every browser this app runs in does.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36'
const KEEP = new Set(['latin', 'latin-ext'])

const css = await (await fetch(SOURCE, { headers: { 'user-agent': UA } })).text()
await mkdir(OUT, { recursive: true })

// A variable family answers the same file for every weight it was asked for, so
// the same URL arrives several times. Fetch and write it once.
const written = new Map()

// The answer is a run of `/* subset */` comments, each followed by one
// @font-face. Split on the comments so a block can be dropped by subset.
const blocks = css.split(/\/\*\s*([a-z-]+)\s*\*\//i).slice(1)
const out = []
const threadFaces = []
let kept = 0

for (let i = 0; i < blocks.length; i += 2) {
  const subset = blocks[i]
  const face = blocks[i + 1]
  if (!KEEP.has(subset)) continue
  const url = /url\((https:\/\/[^)]+\.woff2)\)/.exec(face)?.[1]
  if (!url) continue
  const family = /font-family:\s*'([^']+)'/.exec(face)[1]
  const weight = /font-weight:\s*(\d+)/.exec(face)[1]
  let name = written.get(url)
  if (!name) {
    name = `${family.toLowerCase().replace(/\s+/g, '-')}-${weight}-${subset}.woff2`
    const bytes = Buffer.from(await (await fetch(url, { headers: { 'user-agent': UA } })).arrayBuffer())
    await writeFile(path.join(OUT, name), bytes)
    written.set(url, name)
    process.stdout.write(`fetch-fonts: ${name} (${bytes.length} bytes)\n`)
  }
  out.push(`/* ${subset} */${face.replace(/url\(https:\/\/[^)]+\.woff2\)/, `url(/fonts/${name})`).trimEnd()}`)
  // Keep Classic's existing weight matching. Thread titles alone opt into
  // the bundled Figtree file's continuous 300–900 axis for their 500→650 glide.
  if (family === 'Figtree' && weight === '400') threadFaces.push(`/* ${subset} */${face
    .replace("font-family: 'Figtree'", "font-family: 'Thread Figtree'")
    .replace(/font-weight:\s*400/, 'font-weight: 300 900')
    .replace(/url\(https:\/\/[^)]+\.woff2\)/, `url(/fonts/${name})`).trimEnd()}`)
  kept += 1
}

await writeFile(
  path.join(OUT, 'fonts.css'),
  `/* Generated by tools/fetch-fonts.js. Edit there, never here. */\n${[...out, ...threadFaces].join('\n')}\n`,
)
process.stdout.write(`fetch-fonts: wrote fonts.css with ${kept + threadFaces.length} faces\n`)
